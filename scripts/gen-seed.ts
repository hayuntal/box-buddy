/**
 * Regenerates supabase/seed.sql from the TypeScript catalog, so the two can
 * never drift. Run with `npm run db:seed:gen` after editing src/lib/catalog.ts.
 */
import { writeFileSync } from "node:fs";
import { CATALOG } from "../src/lib/catalog.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (items: readonly string[]) =>
  items.length === 0 ? "'{}'" : `'{${items.join(",")}}'`;

const rows = CATALOG.map(
  (i) =>
    `  (${q(i.slug)}, ${q(i.displayName)}, ${q(i.category)}, ${arr(i.allergens)}, ${arr(i.traits)}, ${i.isStaple})`,
).join(",\n");

const sql = `-- Generated by scripts/gen-seed.ts from src/lib/catalog.ts.
-- Do not edit by hand: run \`npm run db:seed:gen\` instead.

insert into ingredients (slug, display_name, category, allergen_tags, traits, is_staple)
values
${rows}
on conflict (slug) do update set
  display_name = excluded.display_name,
  category = excluded.category,
  allergen_tags = excluded.allergen_tags,
  traits = excluded.traits,
  is_staple = excluded.is_staple;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql (${CATALOG.length} ingredients).`);
